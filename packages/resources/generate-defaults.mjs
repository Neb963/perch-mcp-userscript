import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = fileURLToPath(new URL('.', import.meta.url));
const manifest = JSON.parse(readFileSync(root + 'manifest.json', 'utf8'));
const defaults = manifest.resources.map(item => {
  const body = readFileSync(root + item.path, 'utf8');
  const title = /^# (.+)$/m.exec(body)?.[1] ?? item.id;
  const description = /^description: (.+)$/m.exec(body)?.[1] ?? title;
  return { id: item.id, kind: item.kind, title, description, body, files: {}, enabled: true, dependencies: [], provenance: manifest.provenance, license: 'Original Perch MCP reference text; upstream implementations are not included', upstreamVersion: manifest.version + ':' + item.revision };
});
writeFileSync(root + 'defaults.ts', '// Generated by generate-defaults.mjs from the checked-in manifest and original reference text.\nimport type { ResourceInput } from "../resource-library/src/index.js";\nexport const defaultResources: ResourceInput[] = ' + JSON.stringify(defaults, null, 2) + ';\n');
